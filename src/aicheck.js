// The AI mark in a file's metadata, or null.
export function aiMarker(file) {
  let meta;
  try {
    meta = metadata(file);
  } catch {
    return null;
  }
  if (!meta.length) return null;
  const texts = [meta.toString("utf8"), meta.toString("utf16le"), meta.subarray(1).toString("utf16le")].map((s) => s.toLowerCase());
  return MARKS.find((m) => texts.some((t) => t.includes(m))) || null;
}

// The metadata parts of a file, joined: JPEG APPn/COM segments, PNG text chunks, WebP
// EXIF/XMP chunks, MP4/MOV boxes other than the media data.
function metadata(file) {
  const fd = fs.openSync(file, "r");
  try {
    const size = fs.fstatSync(fd).size;
    const read = (pos, len) => {
      const b = Buffer.alloc(Math.max(0, Math.min(len, size - pos)));
      fs.readSync(fd, b, 0, b.length, pos);
      return b;
    };
    const head = read(0, 12);
    const MB = 1 << 20;
    if (head[0] === 0xff && head[1] === 0xd8) return jpeg(read(0, 8 * MB));
    if (head.toString("latin1", 1, 4) === "PNG") return png(read(0, 64 * MB));
    if (head.toString("latin1", 0, 4) === "RIFF") return riff(read(0, 64 * MB));
    if (["ftyp", "moov", "mdat", "wide", "free", "skip", "uuid"].includes(head.toString("latin1", 4, 8))) return boxes(read, size);
    return Buffer.concat([read(0, MB), read(Math.max(MB, size - MB / 4), MB / 4)]);
  } finally {
    fs.closeSync(fd);
  }
}

function jpeg(b) {
  const out = [];
  let p = 2;
  while (p + 4 <= b.length && b[p] === 0xff) {
    const m = b[p + 1];
    if (m === 0xff) p++;
    else if (m === 0x01 || (m >= 0xd0 && m <= 0xd8)) p += 2;
    else if (m === 0xda || m === 0xd9) break; // image data
    else {
      const len = b.readUInt16BE(p + 2);
      let seg = b.subarray(p + 4, p + 2 + len);
      // C2PA manifests (JUMBF in APP11) are split over segments that each repeat a header.
      if (m === 0xeb && seg.toString("latin1", 0, 2) === "JP" && seg.length > 16) seg = seg.subarray(seg.readUInt32BE(4) > 1 ? 16 : 8);
      if ((m >= 0xe0 && m <= 0xef) || m === 0xfe) out.push(seg);
      p += 2 + len;
    }
  }
  return Buffer.concat(out);
}

const inflate = (b) => {
  try {
    return zlib.inflateSync(b);
  } catch {
    return Buffer.alloc(0);
  }
};

function png(b) {
  const out = [];
  for (let p = 8; p + 12 <= b.length; ) {
    const len = b.readUInt32BE(p);
    const type = b.toString("latin1", p + 4, p + 8);
    const data = b.subarray(p + 8, p + 8 + len);
    if (type === "IEND") break;
    if (type === "zTXt") {
      const k = data.indexOf(0);
      out.push(data.subarray(0, k), inflate(data.subarray(k + 2)));
    } else if (type === "iTXt") {
      const k = data.indexOf(0), lang = data.indexOf(0, k + 3), tk = data.indexOf(0, lang + 1);
      const text = data.subarray(tk + 1);
      out.push(data.subarray(0, tk + 1), data[k + 1] === 1 ? inflate(text) : text);
    } else if (type !== "iCCP" && /^[a-z]/.test(type)) out.push(data); // tEXt, eXIf, caBX (C2PA), ...
    p += 12 + len;
  }
  return Buffer.concat(out);
}

function riff(b) {
  const out = [];
  for (let p = 12; p + 8 <= b.length; ) {
    const id = b.toString("latin1", p, p + 4), len = b.readUInt32LE(p + 4);
    if (!["VP8 ", "VP8L", "VP8X", "ALPH", "ANIM", "ANMF", "ICCP"].includes(id)) out.push(b.subarray(p + 8, p + 8 + len));
    p += 8 + len + (len & 1);
  }
  return Buffer.concat(out);
}

function boxes(read, size) {
  const out = [];
  let total = 0;
  for (let p = 0; p + 8 <= size && total < 16 << 20; ) {
    const h = read(p, 16);
    let len = h.readUInt32BE(0);
    const type = h.toString("latin1", 4, 8);
    if (len === 1) len = Number(h.readBigUInt64BE(8));
    else if (len === 0) len = size - p;
    if (len < 8) break;
    if (!["mdat", "free", "skip", "wide"].includes(type)) {
      const box = read(p, Math.min(len, (16 << 20) - total));
      out.push(box);
      total += box.length;
    }
    p += len;
  }
  return Buffer.concat(out);
}
